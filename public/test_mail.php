<?php
// استدعاء دالة إرسال البريد
require 'mailer.php';

// بيانات الاختبار
$to = 'test@example.com'; // ضع هنا بريدك لتستقبل الرسالة
$subject = 'اختبار إرسال البريد - Eco Friendy';
$message = '
<h2>مرحبا!</h2>
<p>هذه رسالة اختبارية للتأكد من عمل دالة <strong>sendMail()</strong> بنجاح.</p>
<p>إذا وصلت هذه الرسالة، فهذا يعني أن الإعدادات صحيحة.</p>
';

// تجربة إرسال البريد
if(sendMail($to, $subject, $message)) {
    echo "✅ تم إرسال البريد بنجاح إلى: $to";
} else {
    echo "❌ فشل إرسال البريد، تحقق من إعدادات SMTP.";
}
